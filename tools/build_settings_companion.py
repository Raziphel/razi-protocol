#!/usr/bin/env python3
"""Build the optional first-in-list settings companion from Razi Protocol source."""
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "00-razi-protocol-settings"
DIR = ROOT / "companion" / NAME
info = json.loads((DIR / "info.json").read_text(encoding="utf-8"))
version = info["version"]
guard = '''-- Optional early-loading companion owns these same setting IDs when installed.
-- Keep this fallback so Razi Protocol works normally without the companion.
if mods["00-razi-protocol-settings"] then return end

'''
body = (ROOT / "settings.lua").read_text(encoding="utf-8")
assert body.startswith(guard), "Missing exact early-settings guard in root settings.lua"
expected = (
    "-- AUTOGENERATED MIRROR of root settings.lua with the fallback guard removed.\n"
    "-- All setting identifiers/types/defaults must remain identical for saved games.\n"
    'if not mods["razi-protocol"] then return end\n\n'
    + body[len(guard):]
)
(DIR / "settings.lua").write_text(expected, encoding="utf-8")
for lang in ("en", "ru"):
    original = (ROOT / "locale" / lang / "settings.cfg").read_text(encoding="utf-8")
    replaced, count = re.subn(
        r"(?m)^razi-protocol=.*$",
        NAME + "=Razi Protocol",
        original,
        count=1,
    )
    assert count == 1, f"Missing mod-name entry in {lang}"
    dest = DIR / "locale" / lang / "settings.cfg"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(replaced, encoding="utf-8")
zip_path = ROOT / "companion" / "dist" / f"{NAME}_{version}.zip"
zip_path.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
    for rel in ("info.json", "settings.lua", "locale/en/settings.cfg", "locale/ru/settings.cfg"):
        zf.write(DIR / rel, f"{NAME}_{version}/{rel}")
print(f"Built {zip_path.relative_to(ROOT)}")
