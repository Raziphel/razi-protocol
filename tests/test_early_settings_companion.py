import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "00-razi-protocol-settings"
DIR = ROOT / "companion" / NAME

class EarlySettingsCompanionTests(unittest.TestCase):
    def test_fallback_and_mirror_match(self):
        original = (ROOT / "settings.lua").read_text(encoding="utf-8")
        mirror = (DIR / "settings.lua").read_text(encoding="utf-8")
        marker = '''-- Optional early-loading companion owns these same setting IDs when installed.
-- Keep this fallback so Razi Protocol works normally without the companion.
if mods["00-razi-protocol-settings"] then return end

'''
        self.assertTrue(original.startswith(marker))
        self.assertEqual(
            mirror,
            "-- AUTOGENERATED MIRROR of root settings.lua with the fallback guard removed.\n"
            "-- All setting identifiers/types/defaults must remain identical for saved games.\n"
            'if not mods["razi-protocol"] then return end\n\n'
            + original[len(marker):],
        )

    def test_companion_is_early_and_optional(self):
        parent = json.loads((ROOT / "info.json").read_text(encoding="utf-8"))
        shim = json.loads((DIR / "info.json").read_text(encoding="utf-8"))
        self.assertEqual(shim["name"], NAME)
        self.assertEqual(shim["dependencies"], ["base >= 2.1.0"])
        self.assertEqual(parent["name"], "razi-protocol")
        self.assertIn("? "+NAME+" >= "+shim["version"], parent["dependencies"])

    def test_companion_locale_is_in_sync(self):
        for lang in ("en", "ru"):
            original = (ROOT / "locale" / lang / "settings.cfg").read_text(encoding="utf-8")
            mirror = (DIR / "locale" / lang / "settings.cfg").read_text(encoding="utf-8")
            self.assertEqual(
                re.sub(r"(?m)^razi-protocol=.*$", NAME+"=Razi Protocol", original, count=1),
                mirror,
            )

if __name__ == "__main__":
    unittest.main()
